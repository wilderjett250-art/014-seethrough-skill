function formatFrontmatter(item) {
  const frontmatter = item.frontmatter || {};
  const lines = Object.entries(frontmatter).map(([key, value]) => `${key}: ${Array.isArray(value) ? value.join(", ") : value}`);
  const extras = [
    item.lineCount ? `lineCount: ${item.lineCount}` : "",
    item.sizeBytes ? `sizeBytes: ${item.sizeBytes}` : "",
    Number(item.duplicateCount || 1) > 1 ? `duplicateCount: ${item.duplicateCount}` : "",
  ].filter(Boolean);
  const duplicatePaths = item.duplicatePaths && item.duplicatePaths.length > 1
    ? ["", "duplicatePaths:", ...item.duplicatePaths.map((path) => `- ${path}`)]
    : [];
  return [...lines, ...extras, ...duplicatePaths].join("\n") || "没有 frontmatter。";
}

