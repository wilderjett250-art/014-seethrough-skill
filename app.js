function normalizeSnapshot(input) {
  const data = input && typeof input === "object" ? input : {};
  return {
    ...emptySnapshot,
    ...data,
    skills: Array.isArray(data.skills) ? data.skills : [],
    mcpServers: Array.isArray(data.mcpServers) ? data.mcpServers : [],
    presetPaths: Array.isArray(data.presetPaths) ? data.presetPaths : [],
    globalSettings: data.globalSettings || {},
  };
}

function skillItems() {
  const groups = countBy(snapshot.skills.map((item) => skillName(item)));
  return snapshot.skills.map((skill, index) => {
    const name = skillName(skill);
    const raw = skill.rawMarkdown || skill.rawContent || "";
    const description = skill.description || skill.frontmatter?.description || firstMarkdownHeading(raw) || "";
    const source = skill.source || skill.ecosystem || "local";
    return {
      ...skill,
      id: skill.id || stableId(["skill", name, skill.primaryPath || skill.path || index]),
      viewType: "skills",
      name,
      displayName: skill.displayName || skill.frontmatter?.name || name,
      description,
      source,
      category: skill.category || inferCategory(name, `${description}\n${raw}`, skillCategoryRules),
      rawMarkdown: raw,
      primaryPath: skill.primaryPath || skill.path || "",
      directory: skill.directory || "",
      duplicateCount: skill.duplicateCount || groups.get(name) || 1,
      duplicatePaths: Array.isArray(skill.duplicatePaths) ? skill.duplicatePaths : [],
      frontmatter: skill.frontmatter || parseFrontmatter(raw).data,
      lineCount: skill.lineCount || countLines(raw),
      sizeBytes: skill.sizeBytes || byteLength(raw),
      essence: skillEssence(skill, raw, description),
    };
  });
}

function mcpItems() {
  return snapshot.mcpServers.map((server, index) => {
    const name = server.name || server.id || `mcp-${index + 1}`;
    const raw = server.rawConfig || server.raw || buildMcpRaw(server);
    const endpoint = server.url || server.command || server.transport || "未记录启动方式";
    return {
      ...server,
      id: server.id || stableId(["mcp", name, server.configPath || index]),
      viewType: "mcp",
      name,
      displayName: name,
      description: endpoint,
      source: server.configType || server.ecosystem || server.transport || "config",
      category: server.category || inferCategory(name, raw, mcpCategoryRules),
      rawConfig: raw,
      primaryPath: server.configPath || "",
      enabledBool: server.enabledBool !== false && server.enabled !== false && server.enabled !== "false",
      essence: mcpEssence(server),
      sizeBytes: byteLength(raw),
    };
  });
}

