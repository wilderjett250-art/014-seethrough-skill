function hasMostlyChinese(text) {
  const value = String(text || "");
  const chinese = (value.match(/[\u4e00-\u9fa5]/g) || []).length;
  return chinese > Math.max(8, value.length * 0.08);
}

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

