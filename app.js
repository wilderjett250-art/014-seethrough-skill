function sortedItems(items) {
  const mode = document.getElementById("sortSelect").value;
  return [...items].sort((a, b) => {
    if (mode === "category") return a.category.localeCompare(b.category, "zh-CN") || a.name.localeCompare(b.name, "zh-CN");
    if (mode === "source") return String(a.source).localeCompare(String(b.source), "zh-CN") || a.name.localeCompare(b.name, "zh-CN");
    if (mode === "size") return Number(b.sizeBytes || 0) - Number(a.sizeBytes || 0);
    return a.name.localeCompare(b.name, "zh-CN");
  });
}

