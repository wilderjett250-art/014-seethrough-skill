function getInitialLanguage() {
  const saved = localStorage.getItem("seethrough-skill:language");
  if (saved && languageNames[saved]) return saved;
  const browserLanguage = navigator.language || "zh-CN";
  if (languageNames[browserLanguage]) return browserLanguage;
  const shortLanguage = browserLanguage.split("-")[0];
  return languageNames[shortLanguage] ? shortLanguage : "zh-CN";
}

