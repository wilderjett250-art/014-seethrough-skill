function stableId(parts) {
  return parts
    .filter((part) => part !== undefined && part !== null)
    .join("|")
    .toLowerCase()
    .replace(/[^a-z0-9\u4e00-\u9fa5_-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 160) || `item-${Math.random().toString(36).slice(2)}`;
}

function countBy(values) {
  const map = new Map();
  values.forEach((value) => map.set(value, (map.get(value) || 0) + 1));
  return map;
}

function inferCategory(name, text, rules) {
  const corpus = `${name}\n${text || ""}`;
  for (const [label, pattern] of rules) {
    if (pattern.test(corpus)) return label;
  }
  return "其他";
}

function skillEssence(skill, raw, description) {
  const signals = [];
  const text = `${description}\n${raw}`.toLowerCase();
  if (/use this skill|use when|trigger|applies|scope|description:/.test(text)) signals.push("触发边界");
  if (/read|inspect|official|docs?|reference|source|brief|screenshot|context/.test(text)) signals.push("知识来源");
  if (/run|execute|call|script|cli|api|tool|mcp|browser|github|figma|python|node/.test(text)) signals.push("工具路线");
  if (/must|never|avoid|do not|always|prefer|only|required|unless|ask/.test(text)) signals.push("边界约束");
  if (/validate|verify|test|lint|typecheck|build|screenshot|render|compare|evidence|proof|check/.test(text)) signals.push("验证义务");
  if (/output|deliverable|final|report|json|markdown|document|slides|export/.test(text)) signals.push("输出标准");
  const found = signals.length ? signals.join("、") : "未在快照中抽到明显控制点";
  return `局部指令包；它不是工具本身，而是在触发回合里改变模型的判断顺序。当前原文影响点：${found}。`;
}

function mcpEssence(server) {
  const endpoint = server.url ? "远程服务" : server.command ? "本地进程" : "配置入口";
  return `工具入口；它不是提示词，而是把 ${endpoint} 暴露给模型，让模型在任务需要时能调用真实能力。`;
}

