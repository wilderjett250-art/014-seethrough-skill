function parseFrontmatter(raw) {
  const result = { data: {}, body: raw || "" };
  if (!raw || !raw.startsWith("---")) return result;
  const end = raw.indexOf("\n---", 3);
  if (end < 0) return result;
  const block = raw.slice(3, end).trim();
  result.body = raw.slice(end + 4).replace(/^\r?\n/, "");
  block.split(/\r?\n/).forEach((line) => {
    const match = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!match) return;
    result.data[match[1]] = match[2].replace(/^["']|["']$/g, "");
  });
  return result;
}

function firstMarkdownHeading(raw) {
  const match = String(raw || "").match(/^\s{0,3}#\s+(.+)$/m);
  return match ? match[1].trim() : "";
}

function countLines(text) {
  if (!text) return 0;
  return String(text).split(/\r?\n/).length;
}

function byteLength(text) {
  return new TextEncoder().encode(String(text || "")).length;
}

function trimText(text, length) {
  const value = String(text || "");
  return value.length > length ? `${value.slice(0, length - 1)}...` : value;
}

function escapeHtml(value) {
  return String(value || "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function buildMcpRaw(server) {
  const lines = [];
  if (server.configPath) lines.push(`# ${server.configPath}`);
  lines.push(`[mcp_servers.${server.name || server.id || "unknown"}]`);
  ["enabled", "command", "args", "url", "transport", "auth", "startupTimeout", "toolTimeout"].forEach((key) => {
    if (server[key] !== undefined && server[key] !== "") lines.push(`${key} = ${JSON.stringify(server[key])}`);
  });
  return lines.join("\n");
}

